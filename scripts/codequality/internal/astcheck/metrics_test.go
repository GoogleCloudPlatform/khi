func TestOverlapsLines(t *testing.T) {
	testCases := []struct {
		name  string
		start int
		end   int
		set   map[int]struct{}
		want  bool
	}{
		{name: "matches exact end boundary", start: 5, end: 10, set: map[int]struct{}{10: {}}, want: true},
		{name: "returns false when outside range", start: 5, end: 10, set: map[int]struct{}{4: {}, 11: {}}, want: false},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			if got := OverlapsLines(tc.start, tc.end, tc.set); got != tc.want {
				t.Errorf("OverlapsLines(%d, %d) = %v, want %v", tc.start, tc.end, got, tc.want)
			}
		})
	}
}
