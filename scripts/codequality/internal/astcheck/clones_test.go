func TestExtractCloneBlocks(t *testing.T) {
	src := `package a

const LocalConst = 7

func Empty() {}

func AllConstructs(p *int, s []int, ch chan int, pkg struct {
	Field int
	Run   func(int)
}) int {
	defer pkg.Run(1)
	var local int
	_ = local
	total := -1
	for i := 0; i < 2; i++ {
		total += i
	}
	for {
		break
	}
	for _, x := range s {
		if x > 0 {
			ch <- x
		}
		total++
	}
	Empty()
	go Empty()
	_ = pkg.Field
	_ = s[0]
	_ = s[0:1]
	_ = *p
	_ = []int{1, 2}
	_ = (func() func() { return Empty })()()
	switch pkg.Field {
	case LocalConst, pkg.Field, 9:
		return total
	default:
		return 0
	}
}
`
	blocks := ExtractCloneBlocks("./pkg/a/a.go", []byte(src))
	if len(blocks) != 1 {
		t.Fatalf("len(blocks) = %d, want 1", len(blocks))
	}
	var gotTokens []string
	for _, st := range blocks[0].Stmts {
		gotTokens = append(gotTokens, st.Token)
	}
	wantTokens := []string{
		"DEFER(CALL(.Run,1))",
		"DECL",
		"ASSIGN(=,1,$id)",
		"ASSIGN(:=,1,UN(-,$lit:INT))",
		"FOR(BIN(<,$id,$lit:INT))",
		"ASSIGN(:=,1,$lit:INT)",
		"INCDEC(++)",
		"ASSIGN(+=,1,$id)",
		"FOR(_)",
		"BRANCH(break)",
		"RANGE(:=,$id)",
		"IF(BIN(>,$id,$lit:INT))",
		"SEND($id)",
		"INCDEC(++)",
		"EXPR(CALL(Empty,0))",
		"STMT(*ast.GoStmt)",
		"ASSIGN(=,1,SEL(.Field))",
		"ASSIGN(=,1,IDX($id))",
		"ASSIGN(=,1,EX(*ast.SliceExpr))",
		"ASSIGN(=,1,PTR($id))",
		"ASSIGN(=,1,COMP(2))",
		"ASSIGN(=,1,CALL(fn,0))",
		"RET($id)",
		"SWITCH(SEL(.Field))",
		"CASE(LocalConst,.Field,$lit:INT)",
		"RET($id)",
		"CASE(default)",
		"RET($lit:INT)",
	}
	if diff := cmp.Diff(wantTokens, gotTokens); diff != "" {
		t.Errorf("AllConstructs tokens mismatch (-want +got):\n%s", diff)
	}
	if blocks[0].File != "pkg/a/a.go" || blocks[0].FuncName != "AllConstructs" {
		t.Errorf("block metadata = (%q, %q), want (pkg/a/a.go, AllConstructs)", blocks[0].File, blocks[0].FuncName)
	}

	genSrc := "// Code generated by tool. DO NOT EDIT.\npackage p\nfunc Gen() int { return 1 }\n"
	if gotGen := ExtractCloneBlocks("pkg/p/gen.go", []byte(genSrc)); gotGen != nil {
		t.Errorf("ExtractCloneBlocks(generated) = %v, want nil", gotGen)
	}

	errSrc := "package p\nfunc ValidBeforeErr() int { return 1 }\nfunc ("
	if gotErr := ExtractCloneBlocks("pkg/p/bad.go", []byte(errSrc)); gotErr != nil {
		t.Errorf("ExtractCloneBlocks(syntax error) = %v, want nil", gotErr)
	}

	gotSig := joinWindowTokens([]StmtFingerprint{{Token: "A"}, {Token: "B"}})
	if gotSig != "A\nB\n" {
		t.Errorf("joinWindowTokens() = %q, want %q", gotSig, "A\nB\n")
	}
}

func TestCloneIndexFindMaxClone(t *testing.T) {
	srcMiddle := `package a

func TargetMid(xs []int, ch chan int) int {
	ch <- 1
	a := 1
	b := 2
	c := a + b
	if c > 0 {
		return c
	}
	return 0
}

func SameFileShortPeer(ys []int) {
	x := 10
	y := 20
	z := x + y
	_ = z
}

func TargetLongerThanSameFilePeer(zs []int, ch chan int) int {
	ch <- 9
	x := 10
	y := 20
	z := x + y
	_ = z
	if z > 0 {
		ch <- z
	}
	return 0
}
`
	srcPeers := `package b

func PeerFirstTie(xs []int) int {
	defer func() {}()
	u := 1
	v := 2
	w := u + v
	if w > 0 {
		return w
	}
	_ = xs
	return -1
}

func PeerSecondTie(xs []int) int {
	u := 1
	v := 2
	w := u + v
	if w > 0 {
		return w
	}
	return -2
}

func TargetShorterThanPeer() int {
	u := 1
	v := 2
	w := u + v
	return w
}

func LongerPeerForShortTarget(flag bool) int {
	u := 1
	v := 2
	w := u + v
	return w
}
`
	srcOneA := "package a\nfunc SameName() int { return 1 }\n"
	srcOneB := "package b\nfunc SameName() int { return 2 }\n"
	srcEnum := `package c

const (
	KindOne = 1
	KindSix = 6
)

func LabelOne(k int) string {
	switch k {
	case KindOne:
		return "a"
	default:
		return "z"
	}
}

func LabelTwo(k int) string {
	switch k {
	case KindSix:
		return "x"
	default:
		return "w"
	}
}
`

	blocksMid := ExtractCloneBlocks("pkg/a/mid.go", []byte(srcMiddle))
	blocksPeers := ExtractCloneBlocks("pkg/b/peers.go", []byte(srcPeers))
	blocksOneA := ExtractCloneBlocks("pkg/a/one.go", []byte(srcOneA))
	blocksOneB := ExtractCloneBlocks("pkg/b/one.go", []byte(srcOneB))
	blocksEnum := ExtractCloneBlocks("pkg/c/enum.go", []byte(srcEnum))

	// Append extra trailing statement to LongerPeerForShortTarget so target ends first while peer continues.
	longerPeer := blocksPeers[3]
	longerPeer.Stmts = append(longerPeer.Stmts, StmtFingerprint{Token: "DECL", Line: 40})

	testCases := []struct {
		name      string
		minWindow int
		corpus    []FuncCloneBlock
		target    FuncCloneBlock
		wantFound bool
		wantMatch CloneMatch
	}{
		{
			name:      "zero minWindow disables clone matching",
			minWindow: 0,
			corpus:    append(blocksOneA, blocksOneB...),
			target:    blocksOneA[0],
			wantFound: false,
		},
		{
			name:      "minWindow one matches single-statement cross-file same-name function",
			minWindow: 1,
			corpus:    append(blocksOneA, blocksOneB...),
			target:    blocksOneA[0],
			wantFound: true,
			wantMatch: CloneMatch{
				Statements: 1,
				LocalStart: 2,
				LocalEnd:   2,
				PeerFile:   "pkg/b/one.go",
				PeerFunc:   "SameName",
				PeerStart:  2,
				PeerEnd:    2,
			},
		},
		{
			name:      "extends middle clone and preserves first peer on equal length tie",
			minWindow: 2,
			corpus:    []FuncCloneBlock{blocksMid[0], blocksPeers[0], blocksPeers[1]},
			target:    blocksMid[0],
			wantFound: true,
			wantMatch: CloneMatch{
				Statements: 5,
				LocalStart: 5,
				LocalEnd:   9,
				PeerFile:   "pkg/b/peers.go",
				PeerFunc:   "PeerFirstTie",
				PeerStart:  5,
				PeerEnd:    9,
			},
		},
		{
			name:      "stops cleanly at end of shorter target when peer has more statements",
			minWindow: 2,
			corpus:    []FuncCloneBlock{longerPeer},
			target:    blocksPeers[2],
			wantFound: true,
			wantMatch: CloneMatch{
				Statements: 4,
				LocalStart: 26,
				LocalEnd:   29,
				PeerFile:   "pkg/b/peers.go",
				PeerFunc:   "LongerPeerForShortTarget",
				PeerStart:  33,
				PeerEnd:    36,
			},
		},
		{
			name:      "stops cleanly at end of shorter same-file peer when target continues",
			minWindow: 2,
			corpus:    []FuncCloneBlock{blocksMid[1], blocksMid[2]},
			target:    blocksMid[2],
			wantFound: true,
			wantMatch: CloneMatch{
				Statements: 4,
				LocalStart: 23,
				LocalEnd:   26,
				PeerFile:   "pkg/a/mid.go",
				PeerFunc:   "SameFileShortPeer",
				PeerStart:  15,
				PeerEnd:    18,
			},
		},
		{
			name:      "distinct switch case constants do not match as clones",
			minWindow: 4,
			corpus:    blocksEnum,
			target:    blocksEnum[0],
			wantFound: false,
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			idx := NewCloneIndex(tc.minWindow, tc.corpus)
			got, ok := idx.FindMaxClone(tc.target)
			if ok != tc.wantFound {
				t.Fatalf("FindMaxClone() found = %v, want %v (match=%+v)", ok, tc.wantFound, got)
			}
			if diff := cmp.Diff(tc.wantMatch, got); diff != "" {
				t.Errorf("FindMaxClone() mismatch (-want +got):\n%s", diff)
			}
		})
	}
}

func TestDiscoverProdGoFiles(t *testing.T) {
	tmpRepo := t.TempDir()
	for _, rel := range []string{
		"pkg/ok/service.go",
		"pkg/ok/service_test.go",
		"pkg/generated/gen.go",
		"pkg/testutil/mock.go",
		"web/app.go",
		"pkg/vendor/vendored.go",
		"pkg/testdata/fixture.go",
		".git/hooks/hook.go",
	} {
		full := filepath.Join(tmpRepo, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatalf("MkdirAll failed: %v", err)
		}
		if err := os.WriteFile(full, []byte("package p\n"), 0o600); err != nil {
			t.Fatalf("WriteFile failed: %v", err)
		}
	}
	discovered, err := DiscoverProdGoFiles(tmpRepo)
	if err != nil {
		t.Fatalf("DiscoverProdGoFiles() unexpected error: %v", err)
	}
	if diff := cmp.Diff([]string{"pkg/ok/service.go"}, discovered); diff != "" {
		t.Errorf("DiscoverProdGoFiles() mismatch (-want +got):\n%s", diff)
	}
	if missingFiles, missingErr := DiscoverProdGoFiles(filepath.Join(tmpRepo, "does-not-exist")); missingErr != nil || missingFiles != nil {
		t.Errorf("DiscoverProdGoFiles(missing) = (%v, %v), want (nil, nil)", missingFiles, missingErr)
	}

	skipInputs := []string{
		".",
		"pkg/ok",
		".git",
		"a/node_modules",
		"a/vendor",
		"a/testdata",
		"web",
		"pkg/generated",
		"pkg/generated/sub",
		"pkg/testutil",
		"pkg/testutil/fakes",
	}
	gotSkip := make(map[string]bool, len(skipInputs))
	for _, in := range skipInputs {
		gotSkip[in] = shouldSkipWalkDir(in)
	}
	wantSkip := map[string]bool{
		".":                  false,
		"pkg/ok":             false,
		".git":               true,
		"a/node_modules":     true,
		"a/vendor":           true,
		"a/testdata":         true,
		"web":                true,
		"pkg/generated":      true,
		"pkg/generated/sub":  true,
		"pkg/testutil":       true,
		"pkg/testutil/fakes": true,
	}
	if diff := cmp.Diff(wantSkip, gotSkip); diff != "" {
		t.Errorf("shouldSkipWalkDir() mismatch (-want +got):\n%s", diff)
	}
}
