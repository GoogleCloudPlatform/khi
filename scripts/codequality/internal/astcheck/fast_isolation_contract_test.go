type cloneScanOutcome struct {
	Findings    []rule.Finding
	CorpusReads []string
}

func TestCheckFileConventionsFastIsolation(t *testing.T) {
	const brokenSiblingSrc = "package a\nfunc (\n"

	testCases := []struct {
		name     string
		files    map[string]string
		relPaths []string
		want     []ConventionViolation
	}{
		// Returns nil without error when relPaths is empty even if broken Go files exist in the repository.
		{
			name: "empty relPaths ignores broken files",
			files: map[string]string{
				"pkg/a/broken_sibling.go": brokenSiblingSrc,
			},
			relPaths: nil,
			want:     nil,
		},
		// Parses only the valid target file and ignores a syntactically broken sibling in the same directory.
		{
			name: "valid target file ignores broken sibling in same directory",
			files: map[string]string{
				"pkg/a/target.go": `package a

// Config holds target settings.
type Config struct {
	// Name identifies the target.
	Name string
}

// Run executes the target.
func Run() {}

func helper() {}
`,
				"pkg/a/broken_sibling.go": brokenSiblingSrc,
			},
			relPaths: []string{"pkg/a/target.go"},
			want:     nil,
		},
		// Detects decl-visibility-order, exported-member-doc, and no-short-skip on target files without parsing the broken sibling.
		{
			name: "detects visibility order, exported member doc, and no-short-skip with broken sibling present",
			files: map[string]string{
				"pkg/a/target.go": `package a

type privType struct{}

type PubType struct {
	Missing int
}

func privFunc() {}

func PubFunc() {}
`,
				"pkg/a/target_test.go": `package a

import "testing"

func TestSample(t *testing.T) {
	if testing.Short() {
		t.Skip("skip in short")
	}
}
`,
				"pkg/a/broken_sibling.go": brokenSiblingSrc,
			},
			relPaths: []string{"pkg/a/target.go", "pkg/a/target_test.go"},
			want: []ConventionViolation{
				{
					File:    "pkg/a/target.go",
					Line:    5,
					Column:  6,
					Rule:    RuleDeclVisibilityOrder,
					Message: "exported type PubType must appear before unexported types",
				},
				{
					File:    "pkg/a/target.go",
					Line:    6,
					Column:  2,
					Rule:    RuleExportedMemberDoc,
					Message: "exported struct field PubType.Missing must have a GoDoc comment",
				},
				{
					File:    "pkg/a/target.go",
					Line:    11,
					Column:  1,
					Rule:    RuleDeclVisibilityOrder,
					Message: "PubFunc must appear before unexported declarations",
				},
				{
					File:    "pkg/a/target_test.go",
					Line:    7,
					Column:  3,
					Rule:    RuleNoShortSkip,
					Message: "do not call Skip/Skipf/SkipNow inside testing.Short(); scale down iteration counts instead of skipping tests",
				},
			},
		},
		// Skips generated target files while ignoring a broken sibling in the same directory.
		{
			name: "skips generated target file with broken sibling present",
			files: map[string]string{
				"pkg/a/gen.go": `// Code generated by tool. DO NOT EDIT.
package a

type Generated struct {
	Missing int
}
`,
				"pkg/a/broken_sibling.go": brokenSiblingSrc,
			},
			relPaths: []string{"pkg/a/gen.go"},
			want:     nil,
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			repoRoot := writeIsolationFixtureRepo(t, tc.files)

			got, err := CheckFileConventions(repoRoot, tc.relPaths)

			if err != nil {
				t.Fatalf("CheckFileConventions() unexpected error: %v", err)
			}
			if diff := cmp.Diff(tc.want, got); diff != "" {
				t.Errorf("CheckFileConventions() mismatch (-want +got):\n%s", diff)
			}
		})
	}
}

func TestCheckFileConventionsErrors(t *testing.T) {
	testCases := []struct {
		name     string
		files    map[string]string
		relPaths []string
	}{
		// Returns a parse error when the explicitly targeted file has invalid Go syntax.
		{
			name: "syntax error in target file",
			files: map[string]string{
				"pkg/a/target.go": "package a\nfunc (\n",
			},
			relPaths: []string{"pkg/a/target.go"},
		},
		// Returns a read error when the explicitly targeted file is missing.
		{
			name:     "missing target file",
			files:    map[string]string{},
			relPaths: []string{"pkg/a/missing.go"},
		},
	}

	for _, tc := range testCases {
		repoRoot := writeIsolationFixtureRepo(t, tc.files)

		_, err := CheckFileConventions(repoRoot, tc.relPaths)

		if err == nil {
			t.Errorf("%s: CheckFileConventions(%v) error = nil, want error", tc.name, tc.relPaths)
		}
	}
}

func TestEvaluateSkipCloneScan(t *testing.T) {
	th := rule.DefaultThresholds()
	th.Limits[rule.RuleCodeClone] = 4

	files := map[string]string{
		"pkg/a/target.go": `package a

func TargetCalc(xs []int) int {
	total := 0
	scale := 2
	for _, item := range xs {
		total += item * scale
	}
	return total
}
`,
		"pkg/peer/peer.go": `package peer

func PeerCalc(ys []int) int {
	acc := 0
	factor := 2
	for _, val := range ys {
		acc += val * factor
	}
	return acc
}
`,
		"pkg/peer/broken_corpus.go": "package peer\nfunc (\n",
	}

	testCases := []struct {
		name          string
		skipCloneScan bool
		want          cloneScanOutcome
	}{
		// Skips clone indexing and never reads CloneCorpusFiles when SkipCloneScan is true.
		{
			name:          "SkipCloneScan true skips corpus reads and clone findings",
			skipCloneScan: true,
			want: cloneScanOutcome{
				Findings:    nil,
				CorpusReads: nil,
			},
		},
		// Indexes CloneCorpusFiles and detects exact clones when SkipCloneScan is false.
		{
			name:          "SkipCloneScan false reads corpus and detects exact clone",
			skipCloneScan: false,
			want: cloneScanOutcome{
				Findings: []rule.Finding{
					{
						Rule:    rule.RuleCodeClone,
						Kind:    rule.ViolationHardLimit,
						File:    "pkg/a/target.go",
						Line:    4,
						EndLine: 9,
						Subject: "TargetCalc",
						After:   5,
						Limit:   4,
						Detail:  "lines 4-9 duplicate 5 normalized statements from pkg/peer/peer.go:4-9 (PeerCalc)",
					},
				},
				CorpusReads: []string{
					"pkg/peer/broken_corpus.go",
					"pkg/peer/peer.go",
				},
			},
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			var corpusReads []string
			opts := Options{
				Thresholds:             th,
				SkipCloneScan:          tc.skipCloneScan,
				ChangedProdLinesByFile: map[string]map[int]struct{}{"pkg/a/target.go": {4: {}}},
				CloneCorpusFiles:       []string{"pkg/peer/broken_corpus.go", "pkg/peer/peer.go"},
				ReadTargetFile: func(relPath string) ([]byte, error) {
					if strings.HasPrefix(relPath, "pkg/peer/") {
						corpusReads = append(corpusReads, relPath)
					}
					src, ok := files[relPath]
					if !ok {
						return nil, os.ErrNotExist
					}
					return []byte(src), nil
				},
			}

			res, err := Evaluate(opts)

			if err != nil {
				t.Fatalf("Evaluate() unexpected error: %v", err)
			}
			got := cloneScanOutcome{
				Findings:    res.Findings,
				CorpusReads: corpusReads,
			}
			if diff := cmp.Diff(tc.want, got); diff != "" {
				t.Errorf("Evaluate() mismatch (-want +got):\n%s", diff)
			}
		})
	}
}

func writeIsolationFixtureRepo(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for rel, content := range files {
		full := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatalf("os.MkdirAll failed: %v", err)
		}
		if err := os.WriteFile(full, []byte(content), 0o600); err != nil {
			t.Fatalf("os.WriteFile failed: %v", err)
		}
	}
	return root
}
