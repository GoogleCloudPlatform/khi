func TestExtractUnitsFromSource(t *testing.T) {
	type unitSummary struct {
		ID         string
		Key        string
		Kind       simcheck.UnitKind
		StartLine  int
		EndLine    int
		StmtCount  int
		CodeLines  int
		NormPrefix string
	}

	testCases := []struct {
		name string
		src  string
		want []unitSummary
	}{
		{
			name: "extracts exact-boundary and larger units while rejecting sub-threshold stmts or lines",
			src: `package sample

func ExternNoBody(x int) int

func TooFewStmtsEnoughLines() int {
	return (1 +
		2 +
		3 +
		4 +
		5)
}

func EnoughStmtsTooFewLines(x int) int { x++; x++; x++; return x }

func ExactBoundaryFunc(x int) int {
	a := x + 1
	b := a + 2
	return b +
		1
}

func (b *Box[T]) UnwrapItems(items []string) int {
	total := 0
	for _, it := range items {
		if it != "" {
			total++
		}
	}
	return total
}

func (s *Service[K, V]) ProcessItems(items []string) int {
	count := 0
	for _, it := range items {
		if it != "" {
			count++
		}
	}
	return count
}

var singleBoundaryTask = DefineTask(func(x int) int {
	a := x + 1
	b := a + 2
	return b +
		1
})

var tooFewClosureLines = func(x int) int { x++; x++; return x }

var (
	uninitVar   int
	plainVar    = 42
	fewStmtsVar = DefineTask(
		func() int {
			return (1 +
				2 +
				3 +
				4)
		},
	)
	multiTask = DefineTask(
		taskID,
		func(b *Binder) Handler {
			in := Use(b, ref)
			return func() []string {
				vals := in.Get()
				if len(vals) == 0 {
					return nil
				}
				return vals
			}
		},
	)
)
`,
			want: []unitSummary{
				{
					ID:         "pkg/sample/sample.go:ExactBoundaryFunc",
					Key:        "func:ExactBoundaryFunc",
					Kind:       simcheck.KindFunc,
					StartLine:  15,
					EndLine:    20,
					StmtCount:  3,
					CodeLines:  6,
					NormPrefix: "func targetFunc(v1 int) int {",
				},
				{
					ID:         "pkg/sample/sample.go:Box.UnwrapItems",
					Key:        "method:Box.UnwrapItems",
					Kind:       simcheck.KindMethod,
					StartLine:  22,
					EndLine:    30,
					StmtCount:  5,
					CodeLines:  9,
					NormPrefix: "func (v1 *RecvType[v2]) targetFunc(v3 []string) int {",
				},
				{
					ID:         "pkg/sample/sample.go:Service.ProcessItems",
					Key:        "method:Service.ProcessItems",
					Kind:       simcheck.KindMethod,
					StartLine:  32,
					EndLine:    40,
					StmtCount:  5,
					CodeLines:  9,
					NormPrefix: "func (v1 *RecvType[v2, v3]) targetFunc(v4 []string) int {",
				},
				{
					ID:         "pkg/sample/sample.go:singleBoundaryTask",
					Key:        "closure:singleBoundaryTask",
					Kind:       simcheck.KindClosure,
					StartLine:  42,
					EndLine:    47,
					StmtCount:  3,
					CodeLines:  6,
					NormPrefix: "var targetTask = DefineTask(func(v1 int) int {",
				},
				{
					ID:         "pkg/sample/sample.go:multiTask",
					Key:        "closure:multiTask",
					Kind:       simcheck.KindClosure,
					StartLine:  62,
					EndLine:    74,
					StmtCount:  6,
					CodeLines:  13,
					NormPrefix: "var targetTask = DefineTask(",
				},
			},
		},
		{
			name: "skips file with Code generated DO NOT EDIT header",
			src: `// Code generated by mockgen. DO NOT EDIT.
package sample

func GeneratedHelper(items []string) []string {
	out := make([]string, 0, len(items))
	for _, it := range items {
		out = append(out, it)
	}
	return out
}
`,
			want: nil,
		},
	}

	analyzer := NewAnalyzer()
	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			byFile, err := analyzer.ExtractUnits(context.Background(), []simcheck.FileInput{
				{Path: "pkg/sample/sample.go", Content: []byte(tc.src)},
			}, 3, 6)
			if err != nil {
				t.Fatalf("unexpected error: %v", err)
			}
			if tc.want == nil && len(byFile) != 0 {
				t.Errorf("len(byFile) = %d, want 0 when no units extracted", len(byFile))
			}
			var got []unitSummary
			for _, u := range byFile["pkg/sample/sample.go"] {
				prefix := u.NormText
				if idx := strings.IndexByte(prefix, '\n'); idx >= 0 {
					prefix = prefix[:idx]
				}
				got = append(got, unitSummary{
					ID:         u.ID,
					Key:        u.Key,
					Kind:       u.Kind,
					StartLine:  u.StartLine,
					EndLine:    u.EndLine,
					StmtCount:  u.StmtCount,
					CodeLines:  u.CodeLines,
					NormPrefix: prefix,
				})
			}
			if diff := cmp.Diff(tc.want, got); diff != "" {
				t.Errorf("ExtractUnits() mismatch (-want +got):\n%s", diff)
			}
		})
	}
}

func TestExtractUnitsSyntaxError(t *testing.T) {
	if _, err := ExtractUnitsFromSource("pkg/bad.go", []byte("package bad\nfunc {"), 0, 0); err == nil {
		t.Errorf("ExtractUnitsFromSource(invalid Go) succeeded, want error")
	}
}
