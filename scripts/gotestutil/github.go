package gotestutil

import (
	"os"
	"strings"
)

// EscapeAnnotationData escapes message data for GitHub Actions workflow commands.
func EscapeAnnotationData(s string) string {
	r := strings.NewReplacer(
		"%", "%25",
		"\r", "%0D",
		"\n", "%0A",
	)
	return r.Replace(s)
}

// EscapeAnnotationProperty escapes header property values for GitHub Actions workflow commands.
func EscapeAnnotationProperty(s string) string {
	r := strings.NewReplacer(
		"%", "%25",
		"\r", "%0D",
		"\n", "%0A",
		":", "%3A",
		",", "%2C",
	)
	return r.Replace(s)
}

// EscapeMarkdownTable escapes pipe characters inside Markdown table cells.
func EscapeMarkdownTable(s string) string {
	return strings.ReplaceAll(s, "|", `\|`)
}

// AppendSummaryFile appends Markdown report content to the given summary file path.
func AppendSummaryFile(path string, data []byte) error {
	f, err := os.OpenFile(path, os.O_CREATE|os.O_WRONLY|os.O_APPEND, 0o644)
	if err != nil {
		return err
	}
	defer f.Close()
	_, err = f.Write(data)
	return err
}
